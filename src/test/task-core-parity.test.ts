function runCase(op: string, input: Record<string, unknown>): unknown {
  const asTask = (value: unknown) => value as Task;
  const tasks = () => (input.tasks as Row[]).map(asTask);
  switch (op) {
    case "applyTaskStatusTransition": {
      const { tasks: list, taskId, status, extra, failureReason, now } = input as {
        tasks: Row[];
        taskId: string;
        status: TaskStatus;
        extra?: { attentionRequestedAt?: number };
        failureReason?: string;
        now: number;
      };
      const result = applyTaskStatusTransition(
        list.map(asTask),
        taskId,
        status,
        extra,
        failureReason,
        now,
      );
      return { tasks: result.tasks, changed: result.changed, task: result.task ?? null };
    }
    case "shouldIgnoreTaskStatusTransition":
      return shouldIgnoreTaskStatusTransition(
        input.current as TaskStatus,
        input.next as TaskStatus,
      );
    case "archiveTasksInList":
      return archiveTasksInList(
        tasks(),
        input.taskIds as string[],
        input.now as number | undefined,
      );
    case "unarchiveTasksInList":
      return unarchiveTasksInList(tasks(), input.taskIds as string[]);
    case "toggleTaskStarInList":
      return toggleTaskStarInList(tasks(), input.taskId as string);
    case "renameTaskInList":
      return renameTaskInList(tasks(), input.taskId as string, input.name as string);
    case "rollbackTaskMutation":
      return rollbackTaskMutation(asTask(input.current), asTask(input.previous), asTask(input.applied));
    case "applyResolvedTaskSession":
      return applyResolvedTaskSession(
        asTask(input.task),
        input.owner as { agent: AgentOption["value"]; codexLike: boolean; family?: never },
        input.session as { sessionId?: string; sessionPath?: string },
      );
    case "resolveTaskSessionOwner":
      return resolveTaskSessionOwner(asTask(input.task), input.options as AgentOption[]);
    case "getTaskSessionFieldsByFamily":
      return getTaskSessionFieldsByFamily(
        asTask(input.task),
        input.family as never,
      );
    case "hasTaskSession":
      return hasTaskSession(asTask(input.task));
    case "hasTaskSessionPath":
      return hasTaskSessionPath(asTask(input.task));
    case "canNativeResumeWithAgent":
      return canNativeResumeWithAgent(
        asTask(input.task),
        input.target as AgentOption["value"],
        input.options as AgentOption[],
      );
    case "canAdoptSessionForAgent":
      return canAdoptSessionForAgent(
        asTask(input.task),
        input.target as AgentOption["value"],
        input.options as AgentOption[],
      );
    case "resolveConfigSwitchSessionStrategy":
      return resolveConfigSwitchSessionStrategy(
        asTask(input.task),
        input.target as AgentOption["value"],
        input.supported as boolean,
        input.options as AgentOption[],
      );
    case "hasTaskContinuationContext":
      return hasTaskContinuationContext(asTask(input.task));
    case "taskCompletionCommand":
      return taskCompletionCommand(asTask(input.task), input.options as AgentOption[]);
    case "expiredTaskIds":
      return expiredTaskIds(tasks(), input.settings as AutoCleanupSettings, input.nowMs as number);
    case "shouldRunCleanup":
      return shouldRunCleanup(
        input.settings as AutoCleanupSettings,
        input.nowMs as number,
      );
    case "stripTerminalControlSequences":
      return stripTerminalControlSequences(input.value as string);
    case "sanitizeTerminalHistoryForHandoff":
      return sanitizeTerminalHistoryForHandoff(input.value as string);
    default:
      throw new Error(`unhandled operation ${op}`);
  }
}

const computed = CASES.map((item) => ({ ...item, expected: runCase(item.op, item.input) }));

function keyOf(item: { id: string; op: string; input: Record<string, unknown>; expected?: unknown }) {
  return JSON.stringify({ id: item.id, op: item.op, input: item.input, expected: item.expected });
}

describe("task-core-parity: the fixture is what the shipping client actually answers", () => {
  it("every case is answerable by the client and unique", () => {
    const ids = new Set<string>();
    for (const item of CASES) {
      expect(ids.has(item.id), `duplicate case id ${item.id}`).toBe(false);
      ids.add(item.id);
      expect(runCase(item.op, item.input)).toBeDefined();
    }
    expect(CASES.length).toBeGreaterThan(150);
  });

  it("the stored table matches the client's answers, field for field", () => {
    let stored: Case[] | null;
    try {
      stored = JSON.parse(readFileSync(KNOWLEDGE, "utf8")).cases as Case[];
    } catch {
      stored = null;
    }
    if (WRITE) {
      mkdirSync(resolve("core/crates/aeroric-protocol/knowledge"), { recursive: true });
      writeFileSync(
        KNOWLEDGE,
        `${JSON.stringify(
          {
            format: "aeroric.task-parity-cases",
            version: 1,
            generatedBy: "src/test/task-core-parity.test.ts",
            note: "expected values are produced by the shipping client's own TypeScript, never transcribed. Regenerate with AERORIC_WRITE_TASK_EXPECTATIONS=1, then `pnpm native:contracts`.",
            cases: computed,
          },
          null,
          2,
        )}\n`,
        "utf8",
      );
      expect(computed.length).toBeGreaterThan(150);
      return;
    }
    // An absent table is a build error, not a case to assert away: the message names the
    // command that produces it.
    const table = stored;
    if (!table) {
      throw new Error(
        `${KNOWLEDGE} is missing — run AERORIC_WRITE_TASK_EXPECTATIONS=1 pnpm vitest run ${"src/test/task-core-parity.test.ts"}`,
      );
    }
    const storedJson = table.map(keyOf).join("\n");
    const currentJson = computed.map(keyOf).join("\n");
    expect(storedJson).toBe(currentJson);
  });

  it("a declared divergence really diverges, and carries a reason", () => {
    const declared = CASES.filter((item) => item.coreExpected !== undefined);
    for (const item of declared) {
      const client = runCase(item.op, item.input);
      expect(
        JSON.stringify(client) === JSON.stringify(item.coreExpected),
        `${item.id} declares a divergence but both sides answer the same`,
      ).toBe(false);
      expect((item.divergenceReason ?? "").length, `${item.id} needs a reason`).toBeGreaterThan(10);
    }
    // The whole point of P2-04 is that the core inherits the client's rules, so a
    // divergence must stay rare enough to read in a review — an empty list is fine, a long
    // one is not.
    expect(declared.length).toBeLessThan(20);
  });
});
