/* Task P2-04's parity table: the expectations the Rust task machine must reproduce.
 *
 * Same shape as `project-core-parity.test.ts`, and for the same reason. The scenarios
 * below are run through the *shipping client's own functions* — `applyTaskStatusTransition`,
 * `rollbackTaskMutation`, `resolveTaskSessionOwner`, `expiredTaskIds`,
 * `sanitizeTerminalHistoryForHandoff` and the rest — and whatever they answer becomes the
 * fixture `core/crates/aeroric-protocol/knowledge/task-parity-cases.json`, which the Rust
 * core replays. Nobody transcribed a truth: if the product's rule changes, this file is red
 * first.
 *
 * Re-deriving the table is an explicit, reviewable act:
 *   AERORIC_WRITE_TASK_EXPECTATIONS=1 pnpm vitest run src/test/task-core-parity.test.ts
 * and the contract fixture is then regenerated by `pnpm native:contracts`.
 *
 * A case may carry `coreExpected` plus a `divergenceReason` when the core *deliberately*
 * answers differently (the only honest way to migrate behaviour). `task-core-parity` proves
 * a declared divergence really diverges on both sides and that the reason field is not
 * empty; the Rust replay proves it equals `coreExpected`. Both directions, or the
 * declaration is a way to hide a bug.
 */

