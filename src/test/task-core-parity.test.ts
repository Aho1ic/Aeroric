/** A local wall-clock instant, expressed as components so a case reads as "Sunday 20:00"
 *  and not as an opaque epoch. */
function localTime(year: number, month: number, day: number, hour: number, minute = 0): number {
  return new Date(year, month - 1, day, hour, minute, 0, 0).getTime();
}

function offsetMinutesAt(ms: number): number {
  return -new Date(ms).getTimezoneOffset();
}

