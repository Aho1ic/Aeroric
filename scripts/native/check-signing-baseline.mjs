#!/usr/bin/env node
// INV-09: the macOS signing baseline is ad-hoc on purpose.
//
// `src-tauri/tauri.conf.json` must keep `signingIdentity: "-"` and
// `hardenedRuntime: false`; the notarization requirement is met instead by the
// release workflow generating a `tauri.macos-signed.json` overlay at build time.
// Two silent regressions are possible and both are what this checks:
//   * flipping the baseline (a local build would then require a Developer ID and
//     fail in the way AGENTS.md warns about: linker-signed bundles void TCC grants);
//   * deleting a key, because Tauri *defaults* hardenedRuntime to true, so an
//     absent key is a behaviour change that no diff of values would show.
import { readFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const WORKFLOW = ".github/workflows/release-desktop.yml";

/** @returns {string[]} problems; empty means the baseline holds. */
export function baselineProblems(configText, overlayText, workflowText) {
  const problems = [];
  let config;
  try {
    config = JSON.parse(configText);
  } catch (error) {
    return [`tauri.conf.json: unparseable (${error.message}) — refusing to read a broken config as a clean baseline`];
  }
  const macOS = config?.bundle?.macOS;
  if (!macOS || typeof macOS !== "object") {
    return ["tauri.conf.json: no bundle.macOS section — the baseline shape moved, so these assertions prove nothing"];
  }
  if (!("signingIdentity" in macOS)) problems.push('tauri.conf.json: signingIdentity is absent (Tauri would then pick an identity implicitly)');
  else if (macOS.signingIdentity !== "-") problems.push(`tauri.conf.json: signingIdentity is ${JSON.stringify(macOS.signingIdentity)}, INV-09 requires the ad-hoc "-" baseline`);
  if (!("hardenedRuntime" in macOS)) problems.push("tauri.conf.json: hardenedRuntime is absent — Tauri defaults it to true, which is a silent baseline change");
  else if (macOS.hardenedRuntime !== false) problems.push(`tauri.conf.json: hardenedRuntime is ${JSON.stringify(macOS.hardenedRuntime)}, INV-09 requires false in the baseline`);

  if (overlayText === null || overlayText === undefined) {
    // The overlay is generated by CI, so its committed absence is expected; the
    // workflow is what has to keep generating it.
    let wf = "";
    try { wf = workflowText ?? ""; } catch { wf = ""; }
    if (!wf.trim()) {
      problems.push(`${WORKFLOW}: unreadable or empty — cannot confirm the signed CI path re-enables hardenedRuntime`);
    } else {
      if (!/hardenedRuntime:\s*true/.test(wf)) problems.push(`${WORKFLOW}: no longer writes hardenedRuntime=true, so a Developer ID build would ship without the notarization prerequisite`);
      if (!/--config\s+tauri\.macos-signed\.json/.test(wf)) problems.push(`${WORKFLOW}: no longer passes --config tauri.macos-signed.json, so the overlay it writes would have no effect`);
    }
  } else {
    let overlay;
    try { overlay = JSON.parse(overlayText); } catch { overlay = null; }
    if (!overlay) problems.push("tauri.macos-signed.json exists but is unparseable");
    else if (overlay?.bundle?.macOS?.hardenedRuntime !== true) problems.push("tauri.macos-signed.json exists but does not set hardenedRuntime=true");
  }
  return problems;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = (rel) => { try { return readFileSync(path.join(repoRoot, rel), "utf8"); } catch { return null; } };
  const problems = baselineProblems(
    read("src-tauri/tauri.conf.json"),
    read("src-tauri/tauri.macos-signed.json"),
    read(WORKFLOW),
  );
  if (problems.length) {
    console.error("check-signing-baseline: INV-09 violated\n" + problems.map((p) => `  - ${p}`).join("\n"));
    process.exit(1);
  }
  console.log("check-signing-baseline: ad-hoc baseline intact (signingIdentity \"-\", hardenedRuntime false) and the signed CI path still opts back in");
}
