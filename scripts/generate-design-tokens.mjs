import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { cssVariables, motion, radii, spacing, typography } from "../packages/design-system/src/tokens.ts";

const outputPath = fileURLToPath(new URL("../src/styles/design-tokens.generated.css", import.meta.url));
const check = process.argv.includes("--check");
const themeSelectors = { light: ":root", eyecare: "html.eyecare", dark: "html.dark" };
const lines = ["/* Generated by scripts/generate-design-tokens.mjs. */"];
for (const [theme, selector] of Object.entries(themeSelectors)) {
  lines.push(`${selector} {`);
  for (const [name, value] of Object.entries(cssVariables(theme))) {
    lines.push(`  ${name}: ${value};`);
  }
  lines.push("}");
}
lines.push(":root {");
for (const [name, value] of Object.entries(spacing)) lines.push(`  --space-${name}: ${value}px;`);
for (const [name, value] of Object.entries(radii)) lines.push(`  --radius-${name}: ${value}px;`);
for (const [name, value] of Object.entries(typography)) lines.push(`  --font-size-${name}: ${value}px;`);
for (const [name, value] of Object.entries(motion)) lines.push(`  --motion-${name}: ${value}ms;`);
lines.push("}", "");
const generated = lines.join("\n");
if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error("Design tokens are out of date. Run pnpm generate:design-tokens.");
    process.exit(1);
  }
} else {
  await writeFile(outputPath, generated);
}
